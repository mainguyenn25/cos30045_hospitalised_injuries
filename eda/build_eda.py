"""EDA for Stand Up 1: reads the 3 BITRE/AIHW workbooks, writes eda_data.js (for index.html) and summary_stats.md.
Run from anywhere:  python3 eda/build_eda.py   (needs only openpyxl)"""
import json
from pathlib import Path
import openpyxl

HERE = Path(__file__).parent
DATA = HERE.parent / "source-data"
NAT = DATA / "hospitalisation_injury_publication_sep2023.xlsx"
STATE = DATA / "state-and-territory-hospitalisation-injury-publication-2023.xlsx"
FN = DATA / "First-Nations-hospitalised-injuries-2023.xlsx"
YEARS = list(range(2011, 2022))


def table(path, sheet, header_row, n=len(YEARS)):
    """Return (header, rows) for a block of n year-rows starting below header_row (1-based)."""
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True)[sheet]
    rows = list(ws.iter_rows(min_row=header_row, max_row=header_row + n, values_only=True))
    header = [str(h).strip() if h is not None else "" for h in rows[0]]
    body = [r for r in rows[1:] if isinstance(r[0], int)]
    assert [r[0] for r in body] == YEARS, f"{sheet}@{header_row}: unexpected years {[r[0] for r in body]}"
    return header, body


def col(header, rows, name):
    return [r[header.index(name)] for r in rows]


# National trend + road user (T1, T2)
h, t1 = table(NAT, "T1", 2)
total = col(h, t1, "Total")

h, t2 = table(NAT, "T2", 2)
def sum_cols(names):
    return [sum(r[h.index(n)] for n in names) for r in t2]
car = sum_cols(["Car driver", "Car passenger", "Car unknown position"])
road_user = {
    "Car occupant": car,
    "Motorcyclist": col(h, t2, "Motorcyclist"),
    "Pedal cyclist": col(h, t2, "Pedal cyclist"),
    "Pedestrian": col(h, t2, "Pedestrian"),
}
road_user["Other"] = [t - sum(v[i] for v in road_user.values()) for i, t in enumerate(col(h, t2, "Total"))]

# Age x sex (T3.1: Male block header row 4, Female row 18)
AGES = ["0-7", "8-16", "17-25", "26-39", "40-64", "65-74", "75+"]
hm, male = table(NAT, "T3.1", 4)
hf, female = table(NAT, "T3.1", 18)
age_sex_2021 = {"ages": AGES,
                "Male": [male[-1][hm.index(a)] for a in AGES],
                "Female": [female[-1][hf.index(a)] for a in AGES]}
male_tot, female_tot = col(hm, male, "Total"), col(hf, female, "Total")

# Raw national: traffic only, check against T1, bed days per hospitalisation
ws = openpyxl.load_workbook(NAT, read_only=True)["raw"]
hdr = [c for c in next(ws.iter_rows(max_row=1, values_only=True))]
iy, ic, ih, ib = (hdr.index(k) for k in ("Calendar year", "Cause of injury", "Hospitalisations", "Bed days"))
raw_h = {y: 0 for y in YEARS}
raw_b = {y: 0 for y in YEARS}
for r in ws.iter_rows(min_row=2, values_only=True):
    if r[ic] == "Traffic" and r[iy] in raw_h:
        raw_h[r[iy]] += r[ih] or 0
        raw_b[r[iy]] += r[ib] or 0
raw_check = {y: (raw_h[y], total[i]) for i, y in enumerate(YEARS)}

# States (T1, header row 3)
hs, st = table(STATE, "T1", 3)
STATES = ["NSW (a)", "Vic (b)", "Qld", "SA", "WA", "Tas", "NT", "ACT"]
states = {s.split(" ")[0]: col(hs, st, s) for s in STATES}
aus = col(hs, st, "Australia (c)")

# First Nations (T1 header row 3, T4 blocks at rows 4 and 18)
hfn, fn1 = table(FN, "T1", 3)
fn_total = col(hfn, fn1, "First Nations peoples")
nonind_total = col(hfn, fn1, "Non-Indigenous Australians")
AREAS = ["Major Cities", "Regional", "Remote"]
h4a, fnr = table(FN, "T4", 4)
h4b, nir = table(FN, "T4", 18)
def shares(h, row):
    tot = row[h.index("Total")]
    return [round(100 * row[h.index(a)] / tot, 1) for a in AREAS]
remoteness_2021 = {"areas": AREAS, "First Nations peoples": shares(h4a, fnr[-1]),
                   "Non-Indigenous Australians": shares(h4b, nir[-1])}

out = {"years": YEARS, "total": total, "road_user": road_user, "age_sex_2021": age_sex_2021,
       "states": states, "remoteness_2021": remoteness_2021}
(HERE / "eda_data.js").write_text("const EDA = " + json.dumps(out, indent=1) + ";\n")


# Summary stats
def pct(a, b):
    return f"{100 * (b - a) / a:+.1f}%"

i19, i20, i21 = YEARS.index(2019), YEARS.index(2020), YEARS.index(2021)
lines = ["# EDA summary statistics — hospitalised injuries from road crashes, Australia 2011–2021", "",
         "Generated by `eda/build_eda.py` from the three BITRE/AIHW workbooks.", "",
         "## National", "",
         f"- Total hospitalisations 2011–2021: **{sum(total):,}** (mean {sum(total) / len(total):,.0f}/year, "
         f"min {min(total):,} in {YEARS[total.index(min(total))]}, max {max(total):,} in {YEARS[total.index(max(total))]})",
         f"- Change 2011→2021: {pct(total[0], total[-1])}; CAGR {100 * ((total[-1] / total[0]) ** (1 / 10) - 1):.2f}%/year",
         f"- COVID year: 2019→2020 {pct(total[i19], total[i20])}, rebound 2020→2021 {pct(total[i20], total[i21])}",
         f"- Male share: {100 * sum(male_tot) / sum(total):.1f}% of all hospitalisations (2011–2021)",
         f"- Average bed days per hospitalisation (raw sheet, traffic only): 2011 {raw_b[2011] / raw_h[2011]:.2f}, "
         f"2021 {raw_b[2021] / raw_h[2021]:.2f}", "",
         "## Road user (2011 → 2021)", "",
         "| Road user | 2011 | 2021 | Change | Share 2021 |", "|---|---:|---:|---:|---:|"]
for k, v in road_user.items():
    lines.append(f"| {k} | {v[0]:,} | {v[-1]:,} | {pct(v[0], v[-1])} | {100 * v[-1] / total[-1]:.1f}% |")
lines += ["", "## Age × sex (2021)", "", "| Age | Male | Female | Male:Female |", "|---|---:|---:|---:|"]
for a, m, f in zip(AGES, age_sex_2021["Male"], age_sex_2021["Female"]):
    lines.append(f"| {a} | {m:,} | {f:,} | {m / f:.1f} |")
lines += ["", "## State and territory (counts, not rates — needs ABS population)", "",
          "| State | 2011 | 2021 | Change |", "|---|---:|---:|---:|"]
for s, v in states.items():
    lines.append(f"| {s} | {v[0]:,} | {v[-1]:,} | {pct(v[0], v[-1])} |")
lines += ["", "Series breaks: NSW from June 2017, Vic from 2012 — changes across those years are not comparable.", "",
          "## First Nations", "",
          f"- First Nations hospitalisations: {fn_total[0]:,} (2011) → {fn_total[-1]:,} (2021), {pct(fn_total[0], fn_total[-1])} "
          f"vs non-Indigenous {pct(nonind_total[0], nonind_total[-1])}",
          f"- First Nations share of all hospitalisations: {100 * fn_total[0] / total[0]:.1f}% (2011) → {100 * fn_total[-1] / total[-1]:.1f}% (2021)",
          "- Share of each group's 2021 hospitalisations by remoteness (unknown remoteness excluded):", "",
          "| Area | First Nations | Non-Indigenous |", "|---|---:|---:|"]
for a, x, y in zip(AREAS, remoteness_2021["First Nations peoples"], remoteness_2021["Non-Indigenous Australians"]):
    lines.append(f"| {a} | {x}% | {y}% |")
lines += ["", "## Data checks", "",
          "- Raw sheet (Cause = Traffic) yearly hospitalisations vs Table 1: " +
          ("all years match ✅" if all(a == b for a, b in raw_check.values()) else
           "MISMATCH: " + ", ".join(f"{y}: raw {a} vs T1 {b}" for y, (a, b) in raw_check.items() if a != b)),
          "- Sum of states vs Australia: residual (unrecorded/migratory/offshore) per year: " +
          ", ".join(f"{y} {aus[i] - sum(v[i] for v in states.values())}" for i, y in enumerate(YEARS)),
          "- First Nations + non-Indigenous vs total: not-stated residual per year: " +
          ", ".join(f"{y} {total[i] - fn_total[i] - nonind_total[i]}" for i, y in enumerate(YEARS)), ""]
(HERE / "summary_stats.md").write_text("\n".join(lines))
print("\n".join(lines))
